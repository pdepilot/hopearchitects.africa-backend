<?php
declare(strict_types=1);

require_once __DIR__ . '/site_paths.php';

final class SiteSettingsService
{
    private const CONFIG_FILE = 'config/site-settings.php';

    /** @return array<string, mixed> */
    public static function defaults(): array
    {
        return [
            'siteName'        => 'Hope Architects',
            'contactEmail'    => 'info@hopearchitects.ng',
            'contactPhone'    => '+234 808 430 9701',
            'whatsapp'        => '+234 806 389 6199',
            'address'         => '12 Admiralty Way, Lekki Phase 1, Lagos, Nigeria',
            'aboutText'       => 'Hope Architects is a world-class architecture and construction firm delivering visionary design, precision engineering, and exceptional builds across Nigeria.',
            'adminPhone'      => '',
            'socialFacebook'  => 'https://www.facebook.com/hopearchitects',
            'socialInstagram' => 'https://www.instagram.com/hopearchitects',
            'socialTiktok'    => 'https://www.tiktok.com/@hopearchitects',
            'socialTwitter'   => '',
            'businessHours'   => 'Mon – Sat: 9:00 AM – 6:00 PM',
            'siteDesigner'    => 'blinkzcode',
            'updatedAt'       => null,
        ];
    }

    public static function configPath(): string
    {
        return dirname(__DIR__) . '/' . self::CONFIG_FILE;
    }

    /** @return array<string, mixed> */
    public static function get(): array
    {
        $path = self::configPath();
        if (!is_file($path)) {
            return self::defaults();
        }

        $config = require $path;
        return is_array($config) ? array_merge(self::defaults(), $config) : self::defaults();
    }

    /** @param array<string, mixed> $input */
    public static function save(array $input): bool
    {
        $config = [
            'siteName'        => self::clip((string) ($input['siteName'] ?? ''), 120),
            'contactEmail'    => self::clip((string) ($input['contactEmail'] ?? ''), 180),
            'contactPhone'    => self::clip((string) ($input['contactPhone'] ?? ''), 40),
            'whatsapp'        => self::clip((string) ($input['whatsapp'] ?? ''), 40),
            'address'         => self::clip((string) ($input['address'] ?? ''), 500),
            'aboutText'       => self::clip((string) ($input['aboutText'] ?? ''), 2000),
            'adminPhone'      => self::clip((string) ($input['adminPhone'] ?? ''), 40),
            'socialFacebook'  => self::clip((string) ($input['socialFacebook'] ?? ''), 255),
            'socialInstagram' => self::clip((string) ($input['socialInstagram'] ?? ''), 255),
            'socialTiktok'    => self::clip((string) ($input['socialTiktok'] ?? ''), 255),
            'socialTwitter'   => self::clip((string) ($input['socialTwitter'] ?? ''), 255),
            'businessHours'   => self::clip((string) ($input['businessHours'] ?? ''), 200),
            'siteDesigner'    => self::clip((string) ($input['siteDesigner'] ?? 'blinkzcode'), 80),
            'updatedAt'       => date('c'),
        ];

        if ($config['contactEmail'] !== '' && !filter_var($config['contactEmail'], FILTER_VALIDATE_EMAIL)) {
            throw new InvalidArgumentException('Enter a valid contact email.');
        }

        $php = "<?php\n"
            . "declare(strict_types=1);\n\n"
            . "/** Auto-generated by admin settings */\n"
            . 'return ' . var_export($config, true) . ";\n";

        return file_put_contents(self::configPath(), $php) !== false;
    }

    private static function clip(string $value, int $max): string
    {
        $value = trim($value);
        return strlen($value) <= $max ? $value : substr($value, 0, $max);
    }
}
